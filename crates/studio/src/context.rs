fn priority_label(priority: IssuePriority) -> &'static str {
    match priority {
        IssuePriority::None => "none",
        IssuePriority::Low => "low",
        IssuePriority::Medium => "medium",
        IssuePriority::High => "high",
        IssuePriority::Urgent => "urgent",
    }
}

fn write_issues(out: &mut String, root: &Path) {
    let Ok((issues, _)) = list_issues(root) else {
        return;
    };
    if issues.is_empty() {
        return;
    }
    let mut open: Vec<_> = issues
        .iter()
        .filter(|i| i.status != IssueStatus::Done)
        .collect();
    line!(out, "\n## Issues ({} open of {})", open.len(), issues.len());
    let by_status: Vec<String> = IssueStatus::ALL
        .iter()
        .filter_map(|status| {
            let count = issues.iter().filter(|i| i.status == *status).count();
            (count > 0).then(|| format!("{} {count}", status.as_str()))
        })
        .collect();
    line!(out, "- By status: {}", by_status.join(", "));
    let mut by_priority: BTreeMap<IssuePriority, usize> = BTreeMap::new();
    for issue in &open {
        *by_priority.entry(issue.priority).or_default() += 1;
    }
    let priorities: Vec<String> = by_priority
        .iter()
        .rev()
        .map(|(priority, count)| format!("{} {count}", priority_label(*priority)))
        .collect();
    if !priorities.is_empty() {
        line!(out, "- Open by priority: {}", priorities.join(", "));
    }
    if open.is_empty() {
        return;
    }
    open.sort_by(|a, b| b.priority.cmp(&a.priority).then_with(|| a.id.cmp(&b.id)));
    line!(out, "\n### Open issues");
    for issue in open.iter().take(20) {
        let priority = if issue.priority == IssuePriority::None {
            String::new()
        } else {
            format!(" ({})", priority_label(issue.priority))
        };
        line!(
            out,
            "- #{} [{}] {}{priority}{}",
            issue.id,
            issue.status.as_str(),
            issue.title,
            issue
                .assignee
                .as_deref()
                .map(|a| format!(" (@{a})"))
                .unwrap_or_default()
        );
    }
    if open.len() > 20 {
        line!(out, "- … {} more", open.len() - 20);
    }
}

fn write_asset_reviews(out: &mut String, root: &Path) {
    let Ok(metas) = load_asset_meta(root) else {
        return;
    };
    let mut counts: BTreeMap<&str, usize> = BTreeMap::new();
    for meta in metas.values() {
        let label = match meta.status {
            ReviewStatus::None => continue,
            ReviewStatus::Wip => "WIP",
            ReviewStatus::Review => "in review",
            ReviewStatus::Approved => "approved",
            ReviewStatus::Rejected => "changes requested",
        };
        *counts.entry(label).or_default() += 1;
    }
    if counts.is_empty() {
        return;
    }
    let summary = sorted_counts(&counts)
        .into_iter()
        .map(|(label, count)| format!("{label} {count}"))
        .collect::<Vec<_>>()
        .join(", ");
    line!(out, "\n## Asset reviews\n- {summary}");
    let waiting: Vec<_> = metas
        .iter()
        .filter(|(_, m)| m.status == ReviewStatus::Review)
        .map(|(path, _)| format!("`{path}`"))
        .take(10)
        .collect();
    if !waiting.is_empty() {
        line!(out, "- Waiting for review: {}", waiting.join(", "));
    }
}


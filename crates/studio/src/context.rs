fn write_conventions(out: &mut String, family: Option<&str>, tree: &TreeStats) {
    let prefixed: usize = tree.prefixes.values().sum();
    let scripts: usize = tree.script_casing.values().sum();
    if prefixed == 0 && scripts == 0 {
        return;
    }
    line!(out, "\n## Conventions (inferred)");
    if prefixed > 0 && tree.prefix_candidates > 0 {
        let folder = if family == Some("unity") {
            "Assets/"
        } else {
            "Content/"
        };
        let share = prefixed * 100 / tree.prefix_candidates;
        line!(
            out,
            "- {share}% of asset files in `{folder}` use a type prefix. Follow it for new assets:"
        );
        line!(out, "\n| Prefix | Meaning | Files |\n|---|---|---:|");
        for (prefix, count) in sorted_counts(&tree.prefixes).into_iter().take(12) {
            let meaning = PREFIX_MEANINGS
                .iter()
                .find(|(p, _)| *p == prefix)
                .map(|(_, m)| *m)
                .unwrap_or("—");
            line!(out, "| `{prefix}` | {meaning} | {} |", thousands(count));
        }
        line!(out);
    }
    if scripts > 0
        && let Some((style, count)) = sorted_counts(&tree.script_casing).into_iter().next()
    {
        line!(
            out,
            "- Script file names are mostly {style} ({count} of {scripts})."
        );
    }
}

fn write_build_instructions(out: &mut String, family: Option<&str>, unreal: Option<&UnrealFacts>) {
    let steps: Vec<String> = match family {
        Some("unity") => vec![
            "Open the folder in Unity Hub with the editor version above (mismatched versions trigger a full reimport).".into(),
            "Headless build: `Unity -batchmode -quit -projectPath . -buildTarget <Target> -executeMethod <Static.Method> -logFile -`. Pipeline OS presets call `PipelineOS.Build.*` from `Assets/Editor/PipelineOSBuild.cs`.".into(),
            "Tests: `Unity -batchmode -projectPath . -runTests -testPlatform EditMode -testResults results.xml` (no `-quit` with `-runTests`).".into(),
        ],
        Some("unreal") => {
            let uproject = unreal
                .and_then(|u| u.uproject_name.clone())
                .unwrap_or_else(|| "<Project>.uproject".into());
            let target = uproject.trim_end_matches(".uproject");
            vec![
                format!("Open `{uproject}` (right-click > Generate project files first for C++ projects)."),
                format!("Compile the editor: `Engine/Build/BatchFiles/Build.bat {target}Editor Win64 Development -Project=\"<path>/{uproject}\"` (`Build.sh` and `Mac`/`Linux` elsewhere)."),
                format!("Package: `RunUAT BuildCookRun -project=<path>/{uproject} -platform=Win64 -clientconfig=Development -build -cook -stage -pak -archive -archivedirectory=Builds`."),
            ]
        }
        Some("godot") => vec![
            "Open `project.godot` in the Godot version above.".into(),
            "Export headlessly: `godot --headless --path . --export-release \"<preset>\" Builds/<file>` (presets from `export_presets.cfg`, export templates installed).".into(),
            "Run: `godot --path .` (or `--path . res://scene.tscn` for one scene).".into(),
        ],
        Some("blender") => vec![
            "Render: `blender -b file.blend -o //renders/frame_#### -a` (or `-f 1` for one frame).".into(),
            "Scripts: `blender -b file.blend --python script.py --python-exit-code 1`.".into(),
        ],
        _ => Vec::new(),
    };
    if steps.is_empty() {
        return;
    }
    line!(out, "\n## Build & run");
    for (index, step) in steps.iter().enumerate() {
        line!(out, "{}. {step}", index + 1);
    }
    line!(
        out,
        "\nPrefer the project's pipeline tasks below when they exist; they encode the team's exact settings."
    );
}


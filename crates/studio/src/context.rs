//! AI-ready project briefs.
//!
//! An agent dropped into a game or CG project wastes its first minutes (and
//! tokens) discovering what engine it is, which folders are generated, how to
//! build, and what is in flight. The brief answers that up front in compact
//! Markdown: identity, engine, layout with generated folders called out,
//! file-type mix, tasks, open issues, and health. It is served to agents over
//! MCP and the CLI, copied from the desktop app, or written to
//! `.pipelineos/context.md` for tools that read files.

use std::{collections::BTreeMap, fmt::Write as _, path::Path};

use serde::Serialize;

use crate::{
    StudioError,
    issues::{IssueStatus, list_issues},
    metadata_path,
    tasks::load_tasks,
    write_atomic,
};

pub const CONTEXT_FILE: &str = "context.md";

/// Facts the caller already knows from the project config and app state.
#[derive(Debug, Clone, Default, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct BriefInput {
    pub name: String,
    pub project_type: String,
    pub engine: Option<String>,
    pub engine_version: Option<String>,
    pub linked_apps: Vec<String>,
    pub branch: Option<String>,
    pub vcs: Option<String>,
    pub health: Vec<String>,
    pub notes: Option<String>,
}

/// Directories that are generated/caches for common engines; agents should
/// neither read nor edit them.
const GENERATED: &[(&str, &str)] = &[
    ("Library", "Unity cache (generated)"),
    ("Temp", "Unity temp (generated)"),
    ("Logs", "logs (generated)"),
    ("obj", "build intermediates (generated)"),
    ("Intermediate", "Unreal intermediates (generated)"),
    ("Saved", "Unreal saved/autosaves (generated)"),
    ("DerivedDataCache", "Unreal DDC (generated)"),
    ("Binaries", "compiled binaries (generated)"),
    (".godot", "Godot import cache (generated)"),
    ("node_modules", "npm packages (generated)"),
];

fn engine_notes(root: &Path, project_type: &str) -> Vec<String> {
    let mut notes = Vec::new();
    let has = |p: &str| root.join(p).exists();
    match project_type {
        t if t.contains("unity") || has("ProjectSettings/ProjectVersion.txt") => {
            notes.push("Unity project: authored content lives in `Assets/`; packages in `Packages/manifest.json`.".into());
            notes.push("Every asset has a sibling `.meta` file (GUID). Move/rename assets together with their `.meta`, and never hand-edit GUIDs.".into());
            notes.push(
                "Do not edit `Library/`, `Temp/`, or `obj/`; they are regenerated by the editor."
                    .into(),
            );
        }
        t if t.contains("unreal") => {
            notes.push("Unreal project: C++ in `Source/`, content in `Content/` (binary `.uasset`/`.umap`, edit only through the editor).".into());
            notes.push(
                "`Binaries/`, `Intermediate/`, `Saved/`, `DerivedDataCache/` are generated.".into(),
            );
        }
        t if t.contains("godot") || has("project.godot") => {
            notes.push("Godot project: scenes `.tscn` and scripts `.gd` are text and safe to edit; `.godot/` is the import cache.".into());
        }
        t if t.contains("blender") => {
            notes.push("Blender files are binary; automate them with `blender -b file.blend --python script.py`.".into());
        }
        _ => {}
    }
    notes
}

/// Builds the Markdown brief. Reads tasks and issues from the project.
pub fn project_brief(root: &Path, input: &BriefInput) -> Result<String, StudioError> {
    let mut out = String::new();
    let _ = writeln!(out, "# {} — project brief", input.name);
    let _ = writeln!(
        out,
        "\n_Generated by Pipeline OS for AI assistants and new teammates. Paths are relative to `{}`._\n",
        root.display()
    );

    let _ = writeln!(out, "## Overview");
    let _ = writeln!(out, "- Type: {}", input.project_type);
    if let Some(engine) = &input.engine {
        let version = input
            .engine_version
            .as_deref()
            .unwrap_or("unspecified version");
        let _ = writeln!(out, "- Engine: {engine} ({version})");
    }
    if !input.linked_apps.is_empty() {
        let _ = writeln!(out, "- Tools used: {}", input.linked_apps.join(", "));
    }
    match (&input.vcs, &input.branch) {
        (Some(vcs), Some(branch)) => {
            let _ = writeln!(out, "- Version control: {vcs}, branch `{branch}`");
        }
        (Some(vcs), None) => {
            let _ = writeln!(out, "- Version control: {vcs}");
        }
        _ => {}
    }
    if let Some(notes) = input.notes.as_deref().filter(|n| !n.trim().is_empty()) {
        let _ = writeln!(out, "\n## Team notes\n{}", notes.trim());
    }

    let notes = engine_notes(root, &input.project_type);
    if !notes.is_empty() {
        let _ = writeln!(out, "\n## Working in this project");
        for note in notes {
            let _ = writeln!(out, "- {note}");
        }
    }

    let _ = writeln!(out, "\n## Layout");
    let (folders, extensions) = summarize_tree(root);
    for (name, count) in folders.iter().take(25) {
        let label = GENERATED
            .iter()
            .find(|(dir, _)| dir == name)
            .map(|(_, label)| format!(" — {label}"))
            .unwrap_or_default();
        let _ = writeln!(out, "- `{name}/` ({count} files){label}");
    }
    if folders.len() > 25 {
        let _ = writeln!(out, "- … {} more folders", folders.len() - 25);
    }
    if !extensions.is_empty() {
        let mix = extensions
            .iter()
            .take(12)
            .map(|(ext, count)| format!("`.{ext}` {count}"))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(out, "\nFile mix: {mix}");
    }

    if let Ok(tasks) = load_tasks(root)
        && !tasks.is_empty()
    {
        let _ = writeln!(
            out,
            "\n## Pipeline tasks\nRun with `vantadeck tasks run <path> <id> --yes` or the `run_task` MCP tool."
        );
        for task in tasks {
            let detail = task
                .description
                .map(|d| format!(" — {d}"))
                .unwrap_or_default();
            let _ = writeln!(out, "- `{}`: {}{detail}", task.id, task.name);
        }
    }

    if let Ok((issues, _)) = list_issues(root) {
        let open: Vec<_> = issues
            .iter()
            .filter(|i| i.status != IssueStatus::Done)
            .collect();
        if !open.is_empty() {
            let _ = writeln!(out, "\n## Open issues ({})", open.len());
            for issue in open.iter().take(20) {
                let _ = writeln!(
                    out,
                    "- #{} [{}] {}{}",
                    issue.id,
                    issue.status.as_str(),
                    issue.title,
                    issue
                        .assignee
                        .as_deref()
                        .map(|a| format!(" (@{a})"))
                        .unwrap_or_default()
                );
            }
        }
    }

    if !input.health.is_empty() {
        let _ = writeln!(out, "\n## Known health issues");
        for issue in &input.health {
            let _ = writeln!(out, "- {issue}");
        }
    }
    Ok(out)
}

/// Writes the brief to `.pipelineos/context.md` and returns its path.
pub fn write_brief(root: &Path, brief: &str) -> Result<std::path::PathBuf, StudioError> {
    let path = metadata_path(root, CONTEXT_FILE);
    write_atomic(&path, brief)?;
    Ok(path)
}

type Counts = Vec<(String, usize)>;

/// Top-level folder file counts and the most common extensions. Generated
/// folders are counted shallowly (not walked) to stay fast on big projects.
fn summarize_tree(root: &Path) -> (Counts, Counts) {
    let mut folders: BTreeMap<String, usize> = BTreeMap::new();
    let mut extensions: BTreeMap<String, usize> = BTreeMap::new();
    let Ok(entries) = std::fs::read_dir(root) else {
        return (Vec::new(), Vec::new());
    };
    for entry in entries.flatten() {
        let name = entry.file_name().to_string_lossy().into_owned();
        let Ok(kind) = entry.file_type() else {
            continue;
        };
        if !kind.is_dir() || name == ".git" || name == ".pipelineos" {
            continue;
        }
        if GENERATED.iter().any(|(dir, _)| *dir == name) {
            let shallow = std::fs::read_dir(entry.path())
                .map(|d| d.count())
                .unwrap_or(0);
            folders.insert(name, shallow);
            continue;
        }
        let mut count = 0;
        let walker = ignore::WalkBuilder::new(entry.path()).hidden(true).build();
        for file in walker.flatten().take(200_000) {
            if !file.file_type().is_some_and(|t| t.is_file()) {
                continue;
            }
            count += 1;
            if let Some(ext) = file.path().extension().and_then(|e| e.to_str()) {
                let ext = ext.to_ascii_lowercase();
                if ext != "meta" {
                    *extensions.entry(ext).or_default() += 1;
                }
            }
        }
        folders.insert(name, count);
    }
    let mut folders: Counts = folders.into_iter().collect();
    folders.sort_by(|a, b| b.1.cmp(&a.1).then_with(|| a.0.cmp(&b.0)));
    let mut extensions: Counts = extensions.into_iter().collect();
    extensions.sort_by(|a, b| b.1.cmp(&a.1).then_with(|| a.0.cmp(&b.0)));
    (folders, extensions)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::issues::{NewIssue, create_issue};

    #[test]
    fn brief_covers_identity_layout_tasks_and_issues() {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path();
        for file in [
            "Assets/Scripts/Player.cs",
            "Assets/Art/hero.png",
            "Library/x.asset",
        ] {
            let path = root.join(file);
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(path, b"x").unwrap();
        }
        std::fs::create_dir_all(root.join("ProjectSettings")).unwrap();
        std::fs::write(
            root.join("ProjectSettings/ProjectVersion.txt"),
            "m_EditorVersion: 6000.0.1f1",
        )
        .unwrap();
        create_issue(
            root,
            NewIssue {
                title: "Fix jump".into(),
                assignee: Some("sam".into()),
                ..Default::default()
            },
        )
        .unwrap();
        crate::tasks::save_tasks(root, &crate::tasks::task_templates()[..1]).unwrap();

        let brief = project_brief(
            root,
            &BriefInput {
                name: "Voidline".into(),
                project_type: "unity".into(),
                engine: Some("Unity".into()),
                engine_version: Some("6000.0.1f1".into()),
                branch: Some("main".into()),
                vcs: Some("git".into()),
                health: vec!["Git LFS not installed".into()],
                ..Default::default()
            },
        )
        .unwrap();
        assert!(brief.contains("# Voidline"));
        assert!(brief.contains("Unity (6000.0.1f1)"));
        assert!(brief.contains("`.meta`"));
        assert!(brief.contains("`Library/`") && brief.contains("generated"));
        assert!(brief.contains("`Assets/` (2 files)"));
        assert!(brief.contains("unity-build-win64"));
        assert!(brief.contains("Fix jump") && brief.contains("@sam"));
        assert!(brief.contains("Git LFS not installed"));

        let path = write_brief(root, &brief).unwrap();
        assert!(path.ends_with(".pipelineos/context.md"));
    }
}

/// Runs `git -C root <args>` with a timeout; `None` on any failure.
fn git(root: &Path, args: &[&str]) -> Option<String> {
    let mut command = Command::new("git");
    command
        .arg("-C")
        .arg(root)
        .args(args)
        .env("GIT_TERMINAL_PROMPT", "0")
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::null());
    #[cfg(windows)]
    {
        use std::os::windows::process::CommandExt;
        command.creation_flags(0x0800_0000);
    }
    let mut child = command.spawn().ok()?;
    let mut stdout = child.stdout.take()?;
    let reader = std::thread::spawn(move || {
        let mut bytes = Vec::new();
        let _ = stdout.read_to_end(&mut bytes);
        String::from_utf8_lossy(&bytes).into_owned()
    });
    let deadline = Instant::now() + GIT_TIMEOUT;
    loop {
        match child.try_wait() {
            Ok(Some(status)) => {
                let output = reader.join().ok()?;
                return status.success().then_some(output);
            }
            Ok(None) if Instant::now() < deadline => {
                std::thread::sleep(Duration::from_millis(15));
            }
            _ => {
                let _ = child.kill();
                let _ = child.wait();
                return None;
            }
        }
    }
}

/// Removes credentials (`user:token@`), query strings and fragments from a
/// remote URL so it is safe to show and share.
pub fn sanitize_remote_url(url: &str) -> String {
    let url = url.trim();
    let Some((scheme, rest)) = url.split_once("://") else {
        // scp-like `git@host:org/repo.git`: the user is not a secret.
        return url.to_owned();
    };
    let (authority, path) = match rest.find('/') {
        Some(index) => rest.split_at(index),
        None => (rest, ""),
    };
    let host = authority
        .rsplit_once('@')
        .map(|(_, host)| host)
        .unwrap_or(authority);
    let path = path.split(['?', '#']).next().unwrap_or_default();
    format!("{scheme}://{host}{path}")
}

/// Patterns tracked by Git LFS in `.gitattributes`.
fn lfs_patterns(root: &Path) -> Vec<String> {
    std::fs::read_to_string(root.join(".gitattributes"))
        .map(|raw| {
            raw.lines()
                .map(str::trim)
                .filter(|line| !line.starts_with('#') && line.contains("filter=lfs"))
                .filter_map(|line| line.split_whitespace().next().map(str::to_owned))
                .collect()
        })
        .unwrap_or_default()
}

/// Folders an engine's `.gitignore` should cover.
fn expected_ignores(family: Option<&str>) -> &'static [&'static str] {
    match family {
        Some("unity") => &["Library", "Temp", "Obj", "Logs", "UserSettings", "Builds"],
        Some("unreal") => &["Binaries", "Intermediate", "Saved", "DerivedDataCache"],
        Some("godot") => &[".godot"],
        _ => &[],
    }
}

/// Expected generated folders that the root `.gitignore` does not ignore.
fn missing_ignores(root: &Path, family: Option<&str>) -> Option<Vec<&'static str>> {
    let path = root.join(".gitignore");
    if !path.is_file() {
        return None;
    }
    let mut builder = ignore::gitignore::GitignoreBuilder::new(root);
    builder.add(&path);
    let gitignore = builder.build().ok()?;
    Some(
        expected_ignores(family)
            .iter()
            .copied()
            .filter(|dir| {
                let candidate = root.join(dir);
                // Unity's template ignores `[Ll]ibrary/`; also try lowercase.
                let lower = root.join(dir.to_ascii_lowercase());
                !gitignore.matched(&candidate, true).is_ignore()
                    && !gitignore.matched(&lower, true).is_ignore()
            })
            .collect(),
    )
}

fn write_git(out: &mut String, root: &Path, family: Option<&str>, known_branch: Option<&str>) {
    let is_repo = root.join(".git").exists();
    let lfs = lfs_patterns(root);
    let missing = missing_ignores(root, family);
    if !is_repo && lfs.is_empty() && missing.is_none() && expected_ignores(family).is_empty() {
        return;
    }
    line!(out, "\n## Version control");
    if is_repo {
        let branch = known_branch.map(str::to_owned).or_else(|| {
            git(root, &["rev-parse", "--abbrev-ref", "HEAD"]).map(|b| b.trim().to_owned())
        });
        if let Some(branch) = branch.filter(|b| !b.is_empty()) {
            line!(out, "- Branch: `{branch}`");
        }
        if let Some(remote) = git(root, &["remote", "get-url", "origin"])
            .map(|r| r.trim().to_owned())
            .filter(|r| !r.is_empty())
        {
            line!(out, "- Remote `origin`: {}", sanitize_remote_url(&remote));
        }
    }
    match &missing {
        None if !expected_ignores(family).is_empty() => {
            line!(
                out,
                "- **No `.gitignore`**: generated folders may get committed."
            );
        }
        Some(missing) if !missing.is_empty() => {
            let list = missing
                .iter()
                .map(|d| format!("`{d}/`"))
                .collect::<Vec<_>>()
                .join(", ");
            line!(out, "- `.gitignore` does not ignore: {list}");
        }
        Some(_) => {
            line!(out, "- `.gitignore` covers the engine's generated folders.");
        }
        None => {}
    }
    if !lfs.is_empty() {
        let list = lfs
            .iter()
            .take(30)
            .map(|p| format!("`{p}`"))
            .collect::<Vec<_>>()
            .join(", ");
        line!(
            out,
            "- Git LFS tracks: {list}{}",
            if lfs.len() > 30 { " …" } else { "" }
        );
    } else if family.is_some() {
        line!(
            out,
            "- Git LFS: no patterns in `.gitattributes`; large binaries are stored in git directly."
        );
    }
    if !is_repo {
        return;
    }
    if let Some(log) = git(
        root,
        &[
            "log",
            "-10",
            "--no-color",
            "--date=short",
            "--format=%h%x1f%ad%x1f%an%x1f%s",
        ],
    ) {
        let rows: Vec<Vec<&str>> = log
            .lines()
            .map(|line| line.split('\u{1f}').collect::<Vec<_>>())
            .filter(|parts| parts.len() == 4)
            .collect();
        if !rows.is_empty() {
            line!(
                out,
                "\n### Recent commits\n| Commit | Date | Author | Subject |\n|---|---|---|---|"
            );
            for row in rows {
                line!(
                    out,
                    "| `{}` | {} | {} | {} |",
                    row[0],
                    row[1],
                    cell(row[2]),
                    cell(row[3])
                );
            }
        }
    }
    if let Some(shortlog) = git(
        root,
        &["shortlog", "-sn", "--no-merges", "--max-count=5000", "HEAD"],
    ) {
        let people: Vec<String> = shortlog
            .lines()
            .filter_map(|line| {
                let (count, name) = line.trim().split_once('\t')?;
                Some(format!("{} ({})", name.trim(), count.trim()))
            })
            .take(8)
            .collect();
        if !people.is_empty() {
            line!(
                out,
                "\nTop contributors (last 5,000 commits): {}",
                people.join(", ")
            );
        }
    }
}


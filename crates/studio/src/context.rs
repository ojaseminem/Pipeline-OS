pub const CONTEXT_FILE: &str = "context.md";

/// Facts the caller already knows from the project config and app state.
#[derive(Debug, Clone, Default, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct BriefInput {
    pub name: String,
    pub project_type: String,
    pub engine: Option<String>,
    pub engine_version: Option<String>,
    pub linked_apps: Vec<String>,
    pub branch: Option<String>,
    pub vcs: Option<String>,
    pub health: Vec<String>,
    pub notes: Option<String>,
}

/// Directories that are generated/caches for common engines; agents should
/// neither read nor edit them.
const GENERATED: &[(&str, &str)] = &[
    ("Library", "Unity cache (generated)"),
    ("Temp", "Unity temp (generated)"),
    ("Logs", "logs (generated)"),
    ("obj", "build intermediates (generated)"),
    ("UserSettings", "Unity per-user settings (generated)"),
    ("Intermediate", "Unreal intermediates (generated)"),
    ("Saved", "Unreal saved/autosaves (generated)"),
    ("DerivedDataCache", "Unreal DDC (generated)"),
    ("Binaries", "compiled binaries (generated)"),
    (".godot", "Godot import cache (generated)"),
    ("node_modules", "npm packages (generated)"),
];

/// Upper bound on files examined by the brief's tree walk.
const MAX_FILES: usize = 200_000;
/// Each git call is abandoned after this long.
const GIT_TIMEOUT: Duration = Duration::from_secs(4);

macro_rules! line {
    ($out:expr) => {
        let _ = writeln!($out);
    };
    ($out:expr, $($arg:tt)*) => {
        let _ = writeln!($out, $($arg)*);
    };
}

/// Engine family used to pick sections: "unity", "unreal", "godot",
/// "blender", or `None`.
fn engine_family(root: &Path, project_type: &str) -> Option<&'static str> {
    detect_engine(root).or_else(|| {
        let t = project_type.to_ascii_lowercase();
        ["unity", "unreal", "godot", "blender"]
            .into_iter()
            .find(|engine| t.contains(engine))
    })
}

fn engine_notes(family: Option<&str>) -> Vec<String> {
    let mut notes = Vec::new();
    match family {
        Some("unity") => {
            notes.push("Unity project: authored content lives in `Assets/`; packages in `Packages/manifest.json`.".into());
            notes.push("Every asset has a sibling `.meta` file (GUID). Move/rename assets together with their `.meta`, and never hand-edit GUIDs.".into());
            notes.push(
                "Do not edit `Library/`, `Temp/`, or `obj/`; they are regenerated by the editor."
                    .into(),
            );
            notes.push("Scenes (`.unity`), prefabs and `.asset` files are YAML when Asset Serialization is Force Text; edit them in the editor unless you know the format.".into());
        }
        Some("unreal") => {
            notes.push("Unreal project: C++ in `Source/`, content in `Content/` (binary `.uasset`/`.umap`, edit only through the editor).".into());
            notes.push(
                "`Binaries/`, `Intermediate/`, `Saved/`, `DerivedDataCache/` are generated.".into(),
            );
            notes.push("Project settings live in `Config/Default*.ini`; per-user overrides in `Saved/Config` are not shared.".into());
        }
        Some("godot") => {
            notes.push("Godot project: scenes `.tscn` and scripts `.gd` are text and safe to edit; `.godot/` is the import cache.".into());
            notes.push(
                "Resource paths are `res://`-relative; keep them valid when moving files (move inside the editor where possible).".into(),
            );
        }
        Some("blender") => {
            notes.push("Blender files are binary; automate them with `blender -b file.blend --python script.py`.".into());
        }
        _ => {}
    }
    notes
}

/// Generated folders per engine, for the "Do not edit" list.
fn do_not_edit(family: Option<&str>) -> &'static [&'static str] {
    match family {
        Some("unity") => &["Library", "Temp", "Logs", "obj", "UserSettings", "Builds"],
        Some("unreal") => &[
            "Binaries",
            "Intermediate",
            "Saved",
            "DerivedDataCache",
            "Plugins/*/Binaries",
            "Plugins/*/Intermediate",
        ],
        Some("godot") => &[".godot", ".import"],
        _ => &[],
    }
}

/// Builds the Markdown brief. Reads settings, tasks, issues, asset reviews
/// and git history from the project.
pub fn project_brief(root: &Path, input: &BriefInput) -> Result<String, StudioError> {
    let family = engine_family(root, &input.project_type);
    let tree = walk_tree(root);
    let unity = (family == Some("unity")).then(|| UnityFacts::read(root));
    let unreal = (family == Some("unreal")).then(|| UnrealFacts::read(root));
    let godot = (family == Some("godot")).then(|| GodotFacts::read(root));

    let mut out = String::new();
    line!(out, "# {} — project brief", input.name);
    line!(
        out,
        "\n_Generated by Pipeline OS for AI assistants and new teammates. Paths are relative to `{}`._\n",
        root.display()
    );

    // ------------------------------------------------------------ overview
    line!(out, "## Overview");
    line!(out, "- Type: {}", input.project_type);
    let detected_version = unity
        .as_ref()
        .and_then(|u| u.version.clone())
        .or_else(|| unreal.as_ref().and_then(|u| u.engine_association.clone()))
        .or_else(|| godot.as_ref().and_then(|g| g.version.clone()));
    if let Some(engine) = &input.engine {
        let version = input
            .engine_version
            .clone()
            .or(detected_version)
            .unwrap_or_else(|| "unspecified version".into());
        line!(out, "- Engine: {engine} ({version})");
    } else if let Some(family) = family {
        let version = detected_version
            .map(|v| format!(" ({v})"))
            .unwrap_or_default();
        line!(out, "- Engine: {}{version}", title_case(family));
    }
    if !input.linked_apps.is_empty() {
        line!(out, "- Tools used: {}", input.linked_apps.join(", "));
    }
    match (&input.vcs, &input.branch) {
        (Some(vcs), Some(branch)) => {
            line!(out, "- Version control: {vcs}, branch `{branch}`");
        }
        (Some(vcs), None) => {
            line!(out, "- Version control: {vcs}");
        }
        _ => {}
    }
    line!(
        out,
        "- Size: {} files, {}{} (excluding generated and git-ignored folders)",
        thousands(tree.total_files),
        human_bytes(tree.total_bytes),
        if tree.truncated { "+, scan capped" } else { "" }
    );

    if let Some(notes) = input.notes.as_deref().filter(|n| !n.trim().is_empty()) {
        line!(out, "\n## Team notes\n{}", notes.trim());
    }

    // ------------------------------------------------------ engine details
    if let Some(unity) = &unity {
        unity.write(&mut out, &tree);
    }
    if let Some(unreal) = &unreal {
        unreal.write(&mut out, &tree);
    }
    if let Some(godot) = &godot {
        godot.write(&mut out, &tree);
    }

    let notes = engine_notes(family);
    let generated = do_not_edit(family);
    if !notes.is_empty() || !generated.is_empty() {
        line!(out, "\n## Working in this project");
        for note in notes {
            line!(out, "- {note}");
        }
        if !generated.is_empty() {
            let list = generated
                .iter()
                .map(|dir| format!("`{dir}/`"))
                .collect::<Vec<_>>()
                .join(", ");
            line!(out, "- **Do not edit** (generated): {list}");
        }
    }

    write_build_instructions(&mut out, family, unreal.as_ref());
    write_layout(&mut out, &tree);
    write_languages(&mut out, &tree);
    write_conventions(&mut out, family, &tree);
    write_tasks(&mut out, root);
    write_issues(&mut out, root);
    write_asset_reviews(&mut out, root);
    write_git(&mut out, root, family, input.branch.as_deref());

    if !input.health.is_empty() {
        line!(out, "\n## Known health issues");
        for issue in &input.health {
            line!(out, "- {issue}");
        }
    }
    Ok(out)
}

/// Writes the brief to `.pipelineos/context.md` and returns its path.
pub fn write_brief(root: &Path, brief: &str) -> Result<std::path::PathBuf, StudioError> {
    let path = metadata_path(root, CONTEXT_FILE);
    write_atomic(&path, brief)?;
    Ok(path)
}


//! AI-ready project briefs.
//!
//! An agent dropped into a game or CG project wastes its first minutes (and
//! tokens) discovering what engine it is, which folders are generated, how to
//! build, and what is in flight. The brief answers that up front in compact
//! Markdown, without any AI: identity, engine details read from the project's
//! own settings (packages, scenes, modules, plugins, autoloads), layout with
//! generated folders called out, languages and naming conventions, how to
//! build, tasks, issues, asset reviews, version control, and health. It is
//! served to agents over MCP and the CLI, copied from the desktop app, or
//! written to `.pipelineos/context.md` for tools that read files.
//!
//! Every section is best effort: a file that is missing or unreadable (or a
//! `git` that is not installed) drops that section, never the brief.


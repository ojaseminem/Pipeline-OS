#[derive(Debug, Default)]
struct DirStat {
    files: usize,
    generated: Option<&'static str>,
    children: BTreeMap<String, usize>,
}

#[derive(Debug, Default)]
struct TreeStats {
    top: BTreeMap<String, DirStat>,
    root_files: usize,
    extensions: BTreeMap<String, usize>,
    total_files: usize,
    total_bytes: u64,
    truncated: bool,
    /// Project-relative `.umap` paths.
    maps: Vec<String>,
    /// Asset-name prefixes (`SM_`, `T_`...) under Unreal `Content/` or Unity
    /// `Assets/`.
    prefixes: BTreeMap<String, usize>,
    prefix_candidates: usize,
    /// Script file-name casing: style -> count.
    script_casing: BTreeMap<&'static str, usize>,
}

fn generated_label(name: &str) -> Option<&'static str> {
    GENERATED
        .iter()
        .find(|(dir, _)| *dir == name)
        .map(|(_, label)| *label)
}

/// One bounded walk collecting every count the brief needs. Generated
/// folders are counted shallowly (not walked) to stay fast on big projects.
fn walk_tree(root: &Path) -> TreeStats {
    let mut stats = TreeStats::default();
    if let Ok(entries) = std::fs::read_dir(root) {
        for entry in entries.flatten() {
            let name = entry.file_name().to_string_lossy().into_owned();
            if !entry.file_type().is_ok_and(|t| t.is_dir()) || name == ".git" {
                continue;
            }
            if let Some(label) = generated_label(&name) {
                let shallow = std::fs::read_dir(entry.path())
                    .map(|d| d.count())
                    .unwrap_or(0);
                stats.top.insert(
                    name,
                    DirStat {
                        files: shallow,
                        generated: Some(label),
                        ..Default::default()
                    },
                );
            }
        }
    }
    let walker = ignore::WalkBuilder::new(root)
        .hidden(true)
        .filter_entry(|entry| {
            !(entry.file_type().is_some_and(|t| t.is_dir())
                && entry.file_name().to_str().is_some_and(|name| {
                    name == ".git" || name == ".pipelineos" || generated_label(name).is_some()
                }))
        })
        .build();
    for entry in walker.flatten() {
        if !entry.file_type().is_some_and(|t| t.is_file()) {
            continue;
        }
        if stats.total_files >= MAX_FILES {
            stats.truncated = true;
            break;
        }
        let Ok(relative) = entry.path().strip_prefix(root) else {
            continue;
        };
        let parts: Vec<String> = relative
            .components()
            .map(|c| c.as_os_str().to_string_lossy().into_owned())
            .collect();
        stats.total_files += 1;
        stats.total_bytes += entry.metadata().map(|m| m.len()).unwrap_or(0);
        let ext = relative
            .extension()
            .and_then(|e| e.to_str())
            .map(str::to_ascii_lowercase)
            .unwrap_or_default();
        if !ext.is_empty() && ext != "meta" {
            *stats.extensions.entry(ext.clone()).or_default() += 1;
        }
        if parts.len() == 1 {
            stats.root_files += 1;
        } else {
            let dir = stats.top.entry(parts[0].clone()).or_default();
            dir.files += 1;
            if parts.len() > 2 {
                *dir.children.entry(parts[1].clone()).or_default() += 1;
            }
        }
        if ext == "umap" && stats.maps.len() < 200 {
            stats.maps.push(parts.join("/"));
        }
        let stem = relative
            .file_stem()
            .and_then(|s| s.to_str())
            .unwrap_or_default();
        let in_content = parts.len() > 1 && (parts[0] == "Content" || parts[0] == "Assets");
        if in_content && ext != "meta" && !is_script(&ext) {
            stats.prefix_candidates += 1;
            if let Some(prefix) = asset_prefix(stem) {
                *stats.prefixes.entry(prefix).or_default() += 1;
            }
        }
        if is_script(&ext) {
            *stats.script_casing.entry(casing(stem)).or_default() += 1;
        }
    }
    stats
}

fn is_script(ext: &str) -> bool {
    matches!(
        ext,
        "cs" | "gd" | "py" | "cpp" | "h" | "hpp" | "c" | "lua" | "ts" | "js" | "rs"
    )
}

/// `SM_Rock_01` -> `SM_`: one to four letters starting uppercase, then `_`.
fn asset_prefix(stem: &str) -> Option<String> {
    let (head, rest) = stem.split_once('_')?;
    let ok = (1..=4).contains(&head.len())
        && head.chars().next().is_some_and(|c| c.is_ascii_uppercase())
        && head.chars().all(|c| c.is_ascii_alphabetic())
        && !rest.is_empty();
    ok.then(|| format!("{head}_"))
}

fn casing(stem: &str) -> &'static str {
    let has_upper = stem.chars().any(|c| c.is_ascii_uppercase());
    let has_lower = stem.chars().any(|c| c.is_ascii_lowercase());
    if stem.contains('-') {
        "kebab-case"
    } else if stem.contains('_') && !has_upper {
        "snake_case"
    } else if stem.starts_with(|c: char| c.is_ascii_uppercase()) && has_lower {
        if stem.contains('_') {
            "Pascal_Snake"
        } else {
            "PascalCase"
        }
    } else if has_upper && has_lower {
        "camelCase"
    } else {
        "lowercase"
    }
}

fn write_layout(out: &mut String, tree: &TreeStats) {
    line!(out, "\n## Layout");
    let mut folders: Vec<(&String, &DirStat)> = tree.top.iter().collect();
    folders.sort_by(|a, b| {
        a.1.generated
            .is_some()
            .cmp(&b.1.generated.is_some())
            .then(b.1.files.cmp(&a.1.files))
            .then_with(|| a.0.cmp(b.0))
    });
    for (name, stat) in folders.iter().take(25) {
        let label = stat
            .generated
            .map(|label| format!(" — {label}"))
            .unwrap_or_default();
        line!(out, "- `{name}/` ({} files){label}", thousands(stat.files));
        let mut children: Vec<_> = stat.children.iter().collect();
        children.sort_by(|a, b| b.1.cmp(a.1).then_with(|| a.0.cmp(b.0)));
        for (child, count) in children.iter().take(8) {
            line!(out, "  - `{child}/` ({})", thousands(**count));
        }
        if children.len() > 8 {
            line!(out, "  - … {} more", children.len() - 8);
        }
    }
    if folders.len() > 25 {
        line!(out, "- … {} more folders", folders.len() - 25);
    }
    if tree.root_files > 0 {
        line!(out, "- {} files at the top level", tree.root_files);
    }
    if !tree.extensions.is_empty() {
        let mix = sorted_counts(&tree.extensions)
            .into_iter()
            .take(12)
            .map(|(ext, count)| format!("`.{ext}` {count}"))
            .collect::<Vec<_>>()
            .join(", ");
        line!(out, "\nFile mix: {mix}");
    }
}

fn language(ext: &str) -> Option<&'static str> {
    Some(match ext {
        "cs" => "C#",
        "cpp" | "cc" | "cxx" | "h" | "hpp" | "inl" => "C++",
        "c" => "C",
        "gd" => "GDScript",
        "py" => "Python",
        "lua" => "Lua",
        "rs" => "Rust",
        "ts" | "tsx" => "TypeScript",
        "js" | "jsx" | "mjs" => "JavaScript",
        "java" => "Java",
        "kt" | "kts" => "Kotlin",
        "swift" => "Swift",
        "m" | "mm" => "Objective-C",
        "go" => "Go",
        "hlsl" | "glsl" | "shader" | "cginc" | "usf" | "ush" | "compute" | "gdshader" | "wgsl"
        | "vert" | "frag" => "Shaders",
        "shadergraph" | "shadersubgraph" | "vfx" => "Shader/VFX graphs",
        "uxml" | "uss" => "UI Toolkit",
        "mel" => "MEL",
        "vex" | "vfl" => "VEX",
        "sh" | "bash" => "Shell",
        "ps1" => "PowerShell",
        "bat" | "cmd" => "Batch",
        _ => return None,
    })
}

fn write_languages(out: &mut String, tree: &TreeStats) {
    let mut languages: BTreeMap<&str, usize> = BTreeMap::new();
    for (ext, count) in &tree.extensions {
        if let Some(lang) = language(ext) {
            *languages.entry(lang).or_default() += count;
        }
    }
    if languages.is_empty() {
        return;
    }
    line!(out, "\n## Languages");
    line!(out, "| Language | Files |\n|---|---:|");
    for (lang, count) in sorted_counts(&languages).into_iter().take(12) {
        line!(out, "| {lang} | {} |", thousands(count));
    }
}

